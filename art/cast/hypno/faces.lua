-- ---------- implement: the TV screen, map rows 9-14, screen cols 4-11 ----------
local function scr(rows)
  local tails = { "aca", "aaa", "aaa", "aca", "aaa", "aaa" } -- right-hand bezel per row (dial + vents)
  local o, i = {}, 0
  for r in rows:gmatch("[^\n]+") do
    i = i + 1
    o[#o+1] = ".kak"..r.."k"..tails[i].."k."
  end
  return table.concat(o, "\n")
end
