local function uk(eye, glyph)
  local e = UK_EYE[eye]
  local t = { p(1, 4, e[1].."\n"..e[2].."\n"..e[3]) }
  if glyph then
    local o = {}
    for _, r in ipairs(UK_GLYPH[glyph]) do o[#o+1] = ".k"..r.."k." end
    t[#t+1] = p(1, 7, table.concat(o, "\n"))
  end
  return t
end
