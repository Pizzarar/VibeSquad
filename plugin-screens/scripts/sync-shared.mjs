// Copies DOM-free VS logic from ../src into shared/vs/. Paseo's bundler rejects imports from outside
// the plugin's client/, server/ and shared/ dirs, so src/ modules cannot be imported in place.
// `node scripts/sync-shared.mjs --check` exits 1 when a copy has drifted from src/.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "..", "src");
const HEADER = "// GENERATED by scripts/sync-shared.mjs from src/%s. Do not edit; edit src/ and re-run `npm run sync`.\n";

// identity.ts seeds DEFAULT_TEAMS from teams.example.json; the screen always passes the live teams.
const files = {
  "identity.ts": (s) =>
    s.replace(
      'import rawConfig from "../teams.example.json" with { type: "json" };',
      "const rawConfig: { teams?: unknown[] } = { teams: [] };",
    ),
};

const check = process.argv.includes("--check");
let drift = false;
for (const [name, transform] of Object.entries(files)) {
  const want = HEADER.replace("%s", name) + transform(readFileSync(join(src, name), "utf8"));
  const out = join(root, "shared", "vs", name);
  let have = "";
  try { have = readFileSync(out, "utf8"); } catch {}
  if (have === want) continue;
  if (check) { console.error(`drift: shared/vs/${name}`); drift = true; }
  else { writeFileSync(out, want); console.log(`synced shared/vs/${name}`); }
}
process.exit(drift ? 1 : 0);
